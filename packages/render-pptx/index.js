"use strict";

const pptxgen = require("pptxgenjs");
const { validateDeck } = require("../deck-schema");

const THEMES = {
  editorial: { background: "F3EEE5", ink: "242321", muted: "62605A", accent: "A98762", font: "Georgia" },
  modern: { background: "191A20", ink: "F7F7F3", muted: "C4C6CB", accent: "B9FF66", font: "Aptos Display" },
  analytical: { background: "E8EDFF", ink: "182653", muted: "4E5C86", accent: "6575D7", font: "Aptos" }
};

function renderDeck(deck) {
  const validation = validateDeck(deck);
  if (!validation.valid) {
    const error = new Error("Invalid deck: " + validation.errors.join("; "));
    error.code = "INVALID_DECK";
    error.details = validation.errors;
    throw error;
  }

  const theme = THEMES[deck.design.direction] || THEMES.editorial;
  const pptx = new pptxgen();
  pptx.layout = "LAYOUT_WIDE";
  pptx.author = "Design Studio";
  pptx.subject = deck.metadata.brief || "Presentation generated by Design Studio";
  pptx.title = deck.metadata.title || "Design Studio Presentation";
  pptx.company = "Design Studio";
  pptx.lang = "zh-CN";
  pptx.theme = {
    headFontFace: theme.font,
    bodyFontFace: "Aptos",
    lang: "zh-CN"
  };

  deck.slides.forEach((item, index) => {
    const slide = pptx.addSlide();
    slide.background = { color: theme.background };
    slide.addShape(pptx.ShapeType.rect, {
      x: 0, y: 0, w: 0.14, h: 7.5,
      line: { color: theme.accent, transparency: 100 },
      fill: { color: theme.accent }
    });
    if (deck.design.direction === "editorial") {
      slide.addShape(pptx.ShapeType.ellipse, {
        x: 9.5, y: 0.7, w: 2.8, h: 2.8,
        line: { color: theme.accent, width: 1.1, transparency: 12 },
        fill: { color: theme.background, transparency: 100 }
      });
      slide.addShape(pptx.ShapeType.ellipse, {
        x: 9.78, y: 0.98, w: 2.24, h: 2.24,
        line: { color: theme.accent, width: 0.7, transparency: 25 },
        fill: { color: theme.background, transparency: 100 }
      });
    } else if (deck.design.direction === "modern") {
      slide.addShape(pptx.ShapeType.ellipse, {
        x: 10.1, y: 0.7, w: 2.1, h: 2.1,
        line: { color: theme.accent, transparency: 100 },
        fill: { color: theme.accent }
      });
    } else {
      slide.addShape(pptx.ShapeType.line, {
        x: 9.3, y: 2.4, w: 2.4, h: -0.8,
        line: { color: theme.accent, width: 2.2, beginArrowType: "none", endArrowType: "triangle" }
      });
      slide.addShape(pptx.ShapeType.line, {
        x: 9.3, y: 2.4, w: 2.4, h: 0,
        line: { color: theme.accent, width: 1.2 }
      });
    }

    slide.addText("DESIGN STUDIO  /  " + String(index + 1).padStart(2, "0"), {
      x: 0.75, y: 0.65, w: 7.5, h: 0.25,
      fontFace: "Aptos", fontSize: 9, charSpacing: 2.2,
      color: theme.muted, margin: 0, breakLine: false
    });
    const hasImage = typeof item.imageData === "string" && item.imageData.length > 0;
    if (hasImage) {
      slide.addImage({
        data: item.imageData,
        x: 8.0, y: 3.15, w: 4.3, h: 2.65,
        altText: item.imageAlt || item.title || "Slide image"
      });
      if (item.imageSource) slide.addText("Image source: " + item.imageSource, { x: 8.0, y: 5.9, w: 4.3, h: 0.35, fontFace: "Aptos", fontSize: 7, color: theme.muted, margin: 0, fit: "shrink" });
    }
    slide.addText(item.title, {
      x: 0.75, y: 1.55, w: hasImage ? 6.8 : 10.5, h: 1.65,
      fontFace: theme.font, fontSize: 30, bold: true,
      color: theme.ink, margin: 0, breakLine: false,
      valign: "mid", fit: "shrink"
    });
    slide.addText(item.body, {
      x: 0.78, y: 3.55, w: hasImage ? 6.5 : 9.4, h: 1.8,
      fontFace: "Aptos", fontSize: 18, color: theme.muted,
      margin: 0, breakLine: false, valign: "top", fit: "shrink",
      paraSpaceAfterPt: 8
    });
    slide.addText(String(index + 1).padStart(2, "0") + " / " + String(deck.slides.length).padStart(2, "0"), {
      x: 10.8, y: 6.85, w: 1.6, h: 0.25,
      fontFace: "Aptos", fontSize: 9, color: theme.muted,
      align: "right", margin: 0
    });
    if (item.notes) slide.addNotes(item.notes);
  });

  return pptx.write({ outputType: "nodebuffer" });
}

module.exports = { renderDeck, THEMES };
